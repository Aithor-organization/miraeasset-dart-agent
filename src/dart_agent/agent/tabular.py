"""표 원문을 답변 본문에 그대로 싣지 않기 위한 추출 계층 (2026-09-03).

배경 — OOD 실측:
  "삼성전자 실적 요약해줘" → 답변 본문이 `| 구 분 | 제58기 | ... | [유동자산] |
  306,220,075 |` 로 시작하는 **요약재무정보 표의 원문 400자**였다. 사용자는 "요약"을
  요구했는데 받은 것은 원자료다 — 요구사항 충족(지표 3)과 추론 논리성(지표 5)에서
  동시에 감점된다.

왜 narrate()가 못 고치나:
  서술 계층은 **수치 집합 동일성**을 요구한다(narrate.py 안전장치 2번). 표를 요약하면
  숫자가 빠지므로 항상 거부되고 원본 표가 되돌아온다. 즉 표 덤프는 서술 계층의
  하류가 아니라 **상류에서** 막아야 한다.

🔴 줄 단위로 파싱하지 않는다 — DB의 `section.text`는 **개행이 0개인 단일 라인**이다
   (실측: 2,750자 / 줄바꿈 0). 표의 행 경계가 텍스트에 남아 있지 않으므로,
   행을 복원하려 들지 말고 **라벨 바로 뒤의 첫 금액**만 집는다. 표가 파이프 서식이든
   공백 서식이든 이 인접 관계는 깨지지 않는다.

수치는 여전히 만들지 않는다 (D1): 값은 원문 문자열을 그대로 옮기고 재계산하지 않는다.
2개 미만이면 None을 돌려 호출자가 종전 동작으로 떨어지게 한다 — 표를 잘못 읽느니
표를 그대로 보여주는 편이 낫다.
"""

from __future__ import annotations

import re

_PIPE_ROW = re.compile(r"\|[^|\n]*\|[^|\n]*\|")
# 금액 표기 — 천단위 콤마가 있는 수. 연도(2024)·기수(제55기)를 자동 배제한다.
_AMOUNT = r"\(?-?\d{1,3}(?:,\d{3})+\)?"
_UNIT_HINT = re.compile(r"단위\s*[:：]\s*([가-힣]+원)")

# 답변에 실을 재무 항목. 🔴 **긴 것을 먼저** 둔다 — alternation은 좌측 우선이라
#    "자산총계"보다 "자산"이 앞서면 영원히 짧은 쪽만 매칭된다.
_LABELS = (
    "법인세비용차감전순이익", "기본주당순이익", "기본주당이익",
    "당기순이익", "당기순손실", "총포괄손익", "매출총이익",
    "영업이익", "영업손실", "영업수익", "매출액",
    "자산총계", "부채총계", "자본총계",
    "유동자산", "유동부채", "비유동자산", "비유동부채",
)
# 라벨과 금액 사이에 올 수 있는 것: 표 구분자·괄호·공백뿐이다. 다른 글자가 끼면
# 그 라벨의 값이 아니므로 매칭하지 않는다 (인접성이 유일한 근거다).
_ROW = re.compile(
    r"[\[\(]?(" + "|".join(_LABELS) + r")[\]\)]?\s*[|\s]*(" + _AMOUNT + r")"
)
_MAX_ROWS = 6

# 🔴 등장 순서로 자르면 손익이 사라진다. 실측: 요약재무정보 표는 재무상태표가 앞에
#    오므로 상한 6개가 유동자산~부채총계로 다 차고, "실적 요약"의 핵심인 매출액·
#    영업이익·당기순이익이 한 건도 안 남았다. 그래서 **중요도 순으로 고른다**.
_PRIORITY = {
    "매출액": 0, "영업수익": 0, "영업이익": 1, "영업손실": 1,
    "당기순이익": 2, "당기순손실": 2, "매출총이익": 3, "총포괄손익": 4,
    "법인세비용차감전순이익": 5, "기본주당순이익": 6, "기본주당이익": 6,
    "자산총계": 7, "부채총계": 8, "자본총계": 9,
    "유동자산": 10, "유동부채": 11, "비유동자산": 12, "비유동부채": 13,
}


def looks_tabular(text: str) -> bool:
    """본문이 표 원문인지. 파이프 행 2개 이상 또는 금액 5개 이상이면 표로 본다."""
    if not text:
        return False
    if len(_PIPE_ROW.findall(text)) >= 2:
        return True
    return len(re.findall(_AMOUNT, text)) >= 5


def extract_highlights(text: str) -> tuple[str | None, list[tuple[str, str]]]:
    """(단위, [(항목, 값), …]). 값은 원문 문자열 그대로다.

    한 항목이 여러 기수(당기/전기/전전기)를 가지면 **첫 값**만 취한다 — 표는
    최신순으로 배열되므로 첫 열이 당기다. 열 머리글을 해석해 고르려 하면 보고서
    서식마다 달라 틀리므로, 위치 규약만 쓴다.
    """
    unit_m = _UNIT_HINT.search(text)
    unit = unit_m.group(1) if unit_m else None

    found: dict[str, str] = {}
    for m in _ROW.finditer(text):
        found.setdefault(m.group(1), m.group(2))
    picked = sorted(found.items(), key=lambda kv: _PRIORITY.get(kv[0], 99))
    return unit, picked[:_MAX_ROWS]


def summarize(text: str, prefix: str) -> str | None:
    """표 원문 → 한 문장 서술. 뽑은 항목이 2개 미만이면 None (호출자 폴백)."""
    unit, rows = extract_highlights(text)
    if len(rows) < 2:
        return None
    tail = f" (단위: {unit})" if unit else ""
    body = ", ".join(f"{k} {v}" for k, v in rows)
    return f"{prefix} 주요 항목은 {body}입니다{tail}."
